def test_each_finding_is_p1_style_only():
    """находки жаргона — P1, совет по стилю, в оценку не идут: у людей жаргон чаще, чем у моделей"""
    assert WEIGHTS["jargon"] == 0
    for text, _ in [*TRANSLITERATIONS, *CALQUE_WORDS, *GENERAL_JARGON]:
        for i in analyze(text).issues:
            if i.type == "jargon":
                assert i.severity == "P1", text
                assert i.style_only, text


def test_jargon_is_marked_as_style_in_output():
    """в JSON и в таблице scan жаргон идёт как «стиль», и легенда это объясняет"""
    issue = analyze("Собрали пайплайн.").to_dict()["issues"][0]
    assert issue["type"] == "jargon"
    assert issue["styleOnly"] is True
    assert TYPE_LABELS["jargon"] == "Жаргон и транслитерация с английского"
    assert "жаргон" in LEGEND
    assert TYPE_TO_SECTION["jargon"] == TYPE_TO_SECTION["calque"]


def test_every_jargon_rule_is_described_in_catalog():
    """каталог и детектор совпадают: у каждого правила жаргона есть слово в vocabulary.md"""
    catalog = VOCABULARY.read_text(encoding="utf-8").lower()
    for e in ALL_LEXICON:
        if e.type == "jargon":
            assert e.id in catalog or e.id.replace("-", " ") in catalog, e.id


def test_jargon_is_not_a_lightgbm_feature():
    """признаки LightGBM не меняются: новый тип в `rule:` не входит"""
    assert "jargon" not in RULES
    assert "calque" in RULES


def test_jargon_rules_are_unique():
    """у каждого правила жаргона свой идентификатор"""
    ids = [e.id for e in ALL_LEXICON if e.type == "jargon"]
    assert len(ids) == len(set(ids))


