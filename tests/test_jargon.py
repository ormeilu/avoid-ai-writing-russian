# ─── «челлендж»: соревнование или трудность ─────────────────────────────

CONTEST = [
    "Корпуса челленджей Interspeech используют для сравнения.",
    "Бейзлайн челленджа показал 70 %.",
    "Команда приняла участие в челлендже по распознаванию речи.",
    "Задача ComParE челлендж 2024 года остаётся открытой.",
    "На Kaggle выложили новый челлендж с призовым фондом.",
    "На конференции представили челлендж по детекции усталости.",
    "Организаторы соревнования объявили челлендж и дедлайн.",
]
DIFFICULTY = [
    "Главный челлендж проекта — нехватка данных.",
    "Для нас это новый челлендж.",
    "Корпус здания закрыт на ремонт, а челлендж остался.",
    "Конференция закончилась. Потом начался челлендж с бюджетом.",
]


def calque_hits(text: str) -> list[tuple[str, str]]:
    return [(i.rule, i.hint) for i in analyze(text).issues if i.type == "calque" and "челлендж" in i.rule]


@pytest.mark.parametrize("text", CONTEST)
def test_challenge_near_contest_words_means_competition(text: str):
    """рядом с Interspeech, ComParE, Kaggle, конференцией и «участием в» подсказка — «соревнование»"""
    found = calque_hits(text)
    assert [r for r, _ in found] == ["челлендж-соревнование"], text
    assert "соревнование" in found[0][1]


@pytest.mark.parametrize("text", DIFFICULTY)
def test_challenge_elsewhere_means_difficulty(text: str):
    """в остальных случаях прежняя подсказка: «трудность», «задача»"""
    found = calque_hits(text)
    assert [r for r, _ in found] == ["челлендж"], text
    assert "трудность" in found[0][1]


def test_one_occurrence_gives_one_finding():
    """одно вхождение — одна находка, обе записи не срабатывают вместе"""
    for text in [*CONTEST, *DIFFICULTY]:
        assert len(calque_hits(text)) == 1, text
    two = "Челлендж Interspeech объявлен. Главный челлендж проекта — данные."
    assert [r for r, _ in calque_hits(two)] == ["челлендж-соревнование", "челлендж"]


def test_two_challenge_entries_cover_exactly_the_old_one():
    """вместе обе записи ловят то же, что прежнее `челлендж*`: признак `rule:calque` модели не меняется"""
    old = rx("челлендж*")
    entries = [e for e in ALL_LEXICON if e.id.startswith("челлендж")]
    assert len(entries) == 2
    texts = [*CONTEST, *DIFFICULTY, "Челленджи и челленджах без контекста.", "Не челлендж-марафон, а соревнование."]
    for text in texts:
        expected = [m.span() for m in old.finditer(text)]
        got = sorted(m.span() for e in entries for m in e.re.finditer(text))
        assert got == expected, text


def test_challenge_skipped_in_chat():
    """в переписке «челлендж» не ищется, как и раньше"""
    assert calque_hits("Это челлендж Kaggle.") != []
    assert [i for i in analyze("Это челлендж Kaggle.", "chat").issues if i.type == "calque"] == []


