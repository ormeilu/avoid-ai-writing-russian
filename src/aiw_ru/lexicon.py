# ─── Транслитерации, ИТ-жаргон и кальки-слова ───────────────────────────
# Отдельный тип, а не «calque»: признак `rule:calque` модели LightGBM обучен на прежнем
# составе словаря, и новые слова изменили бы его без переобучения. Это и правка стиля,
# а не довод об авторстве: «бейзлайн» и «пайплайн» студенты и разработчики пишут чаще
# моделей. Поэтому P1 (до публикации поправить), но `style_only` и вес 0,5, как у
# канцелярита. Точность важнее полноты: слова с законным вторым значением («пресс-релиз»,
# «кропотливый», «групповая супервизия») ловятся только в том обороте, где значение ясно.
_ENDINGS = "(а|у|е|ом|ы|ов|ам|ами|ах)?"
# «Кроп-фактор», «трекинг-номер»: слово стоит в составе термина.
_NOT_COMPOUND = "(?!-\\p{L})"
# Транслитерации ловятся везде, кроме переписки.
