"""Словари примет.

Каждая запись — регулярное выражение, собранное из мини-языка фраз, и подсказка
по замене. Разделы соответствуют каталогу в references/ основного скилла; соответствие закреплено
в tests/test_lexicon.py.

Мини-язык: слова через пробел; `*` в конце слова — любое окончание (падеж, род,
число, время); `(а|б)` — альтернатива; `?` после группы — необязательная часть.
Текст перед поиском приводится к «е» вместо «ё».
"""

from __future__ import annotations

from dataclasses import dataclass, field

import regex

from aiw_ru.compat import jsre, trim
from aiw_ru.text import WORD_END, WORD_START
from aiw_ru.types import ContextMode, Severity


@dataclass(slots=True, eq=False)
class LexEntry:
    id: str
    type: str
    severity: Severity
    re: regex.Pattern[str]
    hint: str
    style_only: bool = False
    # Режимы, в которых правило не применяется.
    skip: tuple[ContextMode, ...] = ()
    # Порог плотности (вхождений на 1000 слов) по режимам: ниже порога вхождения
    # не считаются находками. Для слов, законных поодиночке.
    density: dict[str, float] = field(default_factory=dict)


_STAR_RE = regex.compile(r"(?<=\p{L})\*")
_SPACES_RE = jsre("\\s+")


def phrase(p: str) -> str:
    # `*` после буквы — любое окончание; `\*` остаётся буквальной звёздочкой.
    body = "[\\s\\u00A0]+".join(_STAR_RE.sub(lambda _: "\\p{L}*", tok) for tok in _SPACES_RE.split(trim(p)))
    return f"{WORD_START}(?:{body}){WORD_END}"


def rx(*phrases: str) -> regex.Pattern[str]:
    return jsre("|".join(phrase(p) for p in phrases), "giu")


def entry(
    type_: str,
    severity: Severity,
    id_: str,
    phrases: str | list[str],
    hint: str,
    *,
    style_only: bool = False,
    skip: tuple[ContextMode, ...] = (),
    density: dict[str, float] | None = None,
) -> LexEntry:
    ps = phrases if isinstance(phrases, list) else [phrases]
    return LexEntry(id_, type_, severity, rx(*ps), hint, style_only, skip, density or {})


