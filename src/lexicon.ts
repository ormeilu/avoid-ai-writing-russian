/**
 * Словари примет. Каждая запись — регулярное выражение, собранное из
 * мини-языка фраз, и подсказка по замене. Разделы соответствуют
 * references/patterns.md; соответствие закреплено в test/lexicon.test.ts.
 *
 * Мини-язык: слова через пробел; `*` в конце слова — любое окончание
 * (падеж, род, число, время); `(а|б)` — альтернатива; `?` после группы —
 * необязательная часть. Текст перед поиском приводится к «е» вместо «ё».
 */

import type { ContextMode, Severity } from "./types.ts";
import { WORD_END, WORD_START } from "./text.ts";

export interface LexEntry {
  id: string;
  type: string;
  severity: Severity;
  re: RegExp;
  hint: string;
  styleOnly?: boolean;
  /** Режимы, в которых правило не применяется. */
  skip?: ContextMode[];
  /**
   * Порог плотности (вхождений на 1000 слов) по режимам: ниже порога
   * вхождения не считаются находками. Для слов, законных поодиночке.
   */
  density?: Partial<Record<ContextMode | "default", number>>;
}

export function phrase(p: string): string {
  const body = p
    .trim()
    .split(/\s+/)
    // `*` после буквы — любое окончание; `\*` остаётся буквальной звёздочкой.
    .map((tok) => tok.replace(/(?<=\p{L})\*/gu, "\\p{L}*"))
    .join("[\\s\\u00A0]+");
  return `${WORD_START}(?:${body})${WORD_END}`;
}

function rx(...phrases: string[]): RegExp {
  return new RegExp(phrases.map(phrase).join("|"), "giu");
}

function entry(
  type: string,
  severity: Severity,
  id: string,
  phrases: string | string[],
  hint: string,
  extra: Partial<LexEntry> = {},
): LexEntry {
  const list = Array.isArray(phrases) ? phrases : [phrases];
  return { id, type, severity, re: rx(...list), hint, ...extra };
}

